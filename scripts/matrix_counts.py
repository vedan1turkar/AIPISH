#!/usr/bin/env python3
"""Recompute requirement-status totals from docs/requirements-matrix.md.

The "## Matrix" table (one row per R1-R60) is the single source of truth. This script:

* counts the Status column and checks that every ID R1-R60 appears exactly once;
* compares the counts with the LAST column of the "## Counts" table (the current totals);
* regenerates the R1-R60 table and totals inside docs/REQUIREMENTS_SUMMARY.md between the
  ``<!-- matrix:begin -->`` / ``<!-- matrix:end -->`` markers.

Usage:
    python3 scripts/matrix_counts.py            # print the counts
    python3 scripts/matrix_counts.py --check    # exit 1 if the Counts table or the summary drifted
    python3 scripts/matrix_counts.py --write    # rewrite the generated block in REQUIREMENTS_SUMMARY.md

Standard library only, so it runs in CI without installing anything.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MATRIX = ROOT / "docs" / "requirements-matrix.md"
SUMMARY = ROOT / "docs" / "REQUIREMENTS_SUMMARY.md"
STATUSES = ["VER", "IMP-U", "PART", "STUB", "MISS", "BLK"]
BEGIN, END = "<!-- matrix:begin -->", "<!-- matrix:end -->"


def _section(text: str, heading: str) -> list[str]:
    lines = text.splitlines()
    try:
        start = next(i for i, ln in enumerate(lines) if ln.strip() == heading)
    except StopIteration:
        raise SystemExit(f"heading {heading!r} not found in {MATRIX}") from None
    out = []
    for ln in lines[start + 1:]:
        if ln.startswith("## "):
            break
        out.append(ln)
    return out


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def matrix_rows(text: str) -> list[dict]:
    rows = []
    for ln in _section(text, "## Matrix"):
        if not ln.startswith("| R"):
            continue
        c = _cells(ln)
        if len(c) < 5:
            raise SystemExit(f"malformed matrix row: {ln[:80]}")
        rid = c[0].rstrip("*")
        rows.append({"id": rid, "star": c[0].endswith("*"), "req": c[1], "status": c[2],
                     "evidence": c[3], "gaps": c[4]})
    return rows


def validate(rows: list[dict]) -> list[str]:
    errs = []
    ids = [r["id"] for r in rows]
    want = [f"R{i}" for i in range(1, 61)]
    for rid in want:
        n = ids.count(rid)
        if n != 1:
            errs.append(f"{rid} appears {n} times in the Matrix table (expected once)")
    for rid in set(ids) - set(want):
        errs.append(f"unexpected ID {rid}")
    for r in rows:
        if r["status"] not in STATUSES:
            errs.append(f"{r['id']}: unknown status {r['status']!r}")
    return errs


def counts(rows: list[dict]) -> dict[str, int]:
    c = Counter(r["status"] for r in rows)
    return {s: c.get(s, 0) for s in STATUSES}


def counts_table_current(text: str) -> tuple[dict[str, int], str]:
    """The last column of the '## Counts' table: the documented current totals."""
    out, header = {}, ""
    for ln in _section(text, "## Counts"):
        if not ln.startswith("|") or set(ln.replace("|", "").strip()) <= set("-: "):
            continue
        c = _cells(ln)
        if c[0] == "Status":
            header = c[-1]
            continue
        key = c[0].strip("*")
        if key in STATUSES or key == "Total":
            out[key] = int(c[-1].strip("*"))
    return out, header


def summary_block(rows: list[dict], cnt: dict[str, int]) -> str:
    total = sum(cnt.values())
    lines = [BEGIN,
             "<!-- Generated by scripts/matrix_counts.py --write from docs/requirements-matrix.md. Do not edit by hand. -->",
             "",
             "| Status | Count |", "|---|---:|"]
    lines += [f"| {s} | {cnt[s]} |" for s in STATUSES]
    lines += [f"| **Total** | {total} |", "",
              "| ID | Requirement | Status | Gaps / external dependency |", "|---|---|---|---|"]
    for r in rows:
        rid = r["id"] + ("*" if r["star"] else "")
        lines.append(f"| {rid} | {r['req']} | {r['status']} | {r['gaps']} |")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="fail on drift")
    g.add_argument("--write", action="store_true", help="regenerate the block in REQUIREMENTS_SUMMARY.md")
    a = ap.parse_args()

    text = MATRIX.read_text(encoding="utf-8")
    rows = matrix_rows(text)
    errs = validate(rows)
    cnt = counts(rows)
    total = sum(cnt.values())
    print("Matrix totals: " + ", ".join(f"{s} {cnt[s]}" for s in STATUSES) + f", Total {total}")

    documented, col = counts_table_current(text)
    want = {**cnt, "Total": total}
    if documented != want:
        errs.append(f"Counts table column {col!r} says {documented}, Matrix table gives {want}")

    block = summary_block(rows, cnt)
    if a.write:
        if not SUMMARY.exists():
            print(f"{SUMMARY} does not exist", file=sys.stderr)
            return 1
        s = SUMMARY.read_text(encoding="utf-8")
        if BEGIN not in s or END not in s:
            print(f"markers missing in {SUMMARY}", file=sys.stderr)
            return 1
        s = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _m: block, s, flags=re.S)
        SUMMARY.write_text(s, encoding="utf-8")
        print(f"wrote {SUMMARY.relative_to(ROOT)}")
    elif SUMMARY.exists():
        s = SUMMARY.read_text(encoding="utf-8")
        m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END), s, flags=re.S)
        if not m or m.group(0) != block:
            errs.append("docs/REQUIREMENTS_SUMMARY.md generated block is stale: run scripts/matrix_counts.py --write")

    for e in errs:
        print("ERROR: " + e, file=sys.stderr)
    if a.check and errs:
        return 1
    return 1 if errs and not a.write else 0


if __name__ == "__main__":
    sys.exit(main())
