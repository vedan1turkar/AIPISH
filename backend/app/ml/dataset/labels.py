"""Target taxonomy and the explicit mapping from every source's original label.

Every (source, original_label) pair that may enter the corpus must appear in
LABEL_MAP; anything else is rejected, so no label is ever inferred silently.
"""
from __future__ import annotations

# The five AIPISH classes (R3). Order is the canonical class index.
LABELS: tuple[str, ...] = ("legitimate", "suspicious", "impersonated", "phishing", "fraud")

# (source, original_label) -> (target_label, rationale)
LABEL_MAP: dict[tuple[str, str], tuple[str, str]] = {
    ("nazario", "phishing"): (
        "phishing", "Hand-classified phishing by the corpus author; label kept as-is."),
    ("spamassassin", "easy_ham"): (
        "legitimate", "SpamAssassin 'ham' (non-spam), easy subset."),
    ("spamassassin", "easy_ham_2"): (
        "legitimate", "SpamAssassin 'ham' (non-spam), later easy subset."),
    ("spamassassin", "hard_ham"): (
        "legitimate", "SpamAssassin 'ham' that resembles spam (HTML, marketing); still non-spam."),
    ("enron", "sent_mail"): (
        "legitimate", "Enron has no labels. Only custodians' own sent folders are used, i.e. "
                      "mail authored by employees; mapped to legitimate (documented assumption)."),
    # Synthetic families (generated by app.ml.dataset.synthetic). Precedence
    # rule: a request to move money / change payment details => fraud;
    # posing as a known person/brand without a payment or credential ask
    # => impersonated.
    ("synthetic", "bec_wire_transfer"): ("fraud", "Synthetic BEC: urgent wire/payment request."),
    ("synthetic", "bec_payroll_redirect"): ("fraud", "Synthetic BEC: payroll bank-detail change."),
    ("synthetic", "invoice_bank_change"): ("fraud", "Synthetic vendor invoice with changed remittance account."),
    ("synthetic", "gift_card_request"): ("fraud", "Synthetic gift-card purchase request."),
    ("synthetic", "advance_fee"): ("fraud", "Synthetic advance-fee / prize / inheritance scam."),
    ("synthetic", "exec_impersonation"): (
        "impersonated", "Synthetic display-name/lookalike executive asking for a non-financial action."),
    ("synthetic", "vendor_impersonation"): (
        "impersonated", "Synthetic lookalike supplier/partner asking for documents or contacts."),
    ("synthetic", "it_support_impersonation"): (
        "impersonated", "Synthetic lookalike IT/HR contact asking for a call-back or data, no link."),
}


def map_label(source: str, original_label: str) -> str:
    """Return the target class; raise KeyError for an unmapped pair."""
    try:
        target = LABEL_MAP[(source, original_label)][0]
    except KeyError:
        raise KeyError(f"no label mapping for source={source!r} original_label={original_label!r}") from None
    assert target in LABELS
    return target
